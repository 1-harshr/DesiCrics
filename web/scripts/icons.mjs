// Turns the Android app's vector drawables (Material Symbols plus our own) into SVG markup for the web
// design system, so both apps draw the same icons. Run with `npm run icons` after adding a drawable.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const source = new URL("../../app/designsystem/src/commonMain/composeResources/drawable/", import.meta.url).pathname;
const target = new URL("../src/designsystem/icons.generated.ts", import.meta.url).pathname;

const attr = (tag, name) => tag.match(new RegExp(`android:${name}="([^"]*)"`))?.[1];

/** `#AARRGGBB` → [colour, opacity]. Opaque black means "use the text colour". */
function colour(value) {
  if (!value) return null;
  const hex = value.replace("#", "");
  const [alpha, rgb] = hex.length === 8 ? [parseInt(hex.slice(0, 2), 16) / 255, hex.slice(2)] : [1, hex];
  return [rgb.toUpperCase() === "000000" ? "currentColor" : `#${rgb}`, alpha];
}

function convert(xml) {
  const body = xml.replace(/<!--[\s\S]*?-->/g, "");
  const vector = body.match(/<vector[^>]*>/)[0];
  const out = [];
  for (const [tag] of body.matchAll(/<\/?group[^>]*>|<path[^>]*\/>/g)) {
    if (tag.startsWith("</group")) {
      out.push("</g>");
    } else if (tag.startsWith("<group")) {
      const transforms = [];
      const tx = attr(tag, "translateX") ?? 0;
      const ty = attr(tag, "translateY") ?? 0;
      if (tx || ty) transforms.push(`translate(${tx} ${ty})`);
      const rotation = attr(tag, "rotation");
      if (rotation) transforms.push(`rotate(${rotation} ${attr(tag, "pivotX") ?? 0} ${attr(tag, "pivotY") ?? 0})`);
      out.push(transforms.length ? `<g transform="${transforms.join(" ")}">` : "<g>");
    } else {
      const parts = [`d="${attr(tag, "pathData")}"`];
      const fill = colour(attr(tag, "fillColor"));
      parts.push(fill ? `fill="${fill[0]}"` : `fill="none"`);
      if (fill && fill[1] < 1) parts.push(`fill-opacity="${fill[1].toFixed(2)}"`);
      const stroke = colour(attr(tag, "strokeColor"));
      if (stroke) {
        parts.push(`stroke="${stroke[0]}"`, `stroke-width="${attr(tag, "strokeWidth") ?? 1}"`);
        const alpha = Number(attr(tag, "strokeAlpha") ?? 1) * stroke[1];
        if (alpha < 1) parts.push(`stroke-opacity="${alpha.toFixed(2)}"`);
        const cap = attr(tag, "strokeLineCap");
        if (cap) parts.push(`stroke-linecap="${cap}"`);
        const join = attr(tag, "strokeLineJoin");
        if (join) parts.push(`stroke-linejoin="${join}"`);
      }
      out.push(`<path ${parts.join(" ")}/>`);
    }
  }
  return {
    viewBox: `0 0 ${attr(vector, "viewportWidth")} ${attr(vector, "viewportHeight")}`,
    mirrored: attr(vector, "autoMirrored") === "true",
    body: out.join(""),
  };
}

const icons = {};
const illustrations = {};
for (const file of readdirSync(source).sort()) {
  const match = file.match(/^(ic|ill)_(.+)\.xml$/);
  if (!match) continue;
  (match[1] === "ic" ? icons : illustrations)[match[2]] = convert(readFileSync(join(source, file), "utf8"));
}

writeFileSync(
  target,
  `// Generated by scripts/icons.mjs from the Android app's drawables. Don't edit; run \`npm run icons\`.\n\n` +
    `export type VectorArt = { viewBox: string; mirrored: boolean; body: string };\n\n` +
    `export const icons = ${JSON.stringify(icons, null, 2)} satisfies Record<string, VectorArt>;\n\n` +
    `export const illustrations = ${JSON.stringify(illustrations, null, 2)} satisfies Record<string, VectorArt>;\n\n` +
    `export type IconName = keyof typeof icons;\nexport type IllustrationName = keyof typeof illustrations;\n`,
);
console.log(`${Object.keys(icons).length} icons, ${Object.keys(illustrations).length} illustrations`);
